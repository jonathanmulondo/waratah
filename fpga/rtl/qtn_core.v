//-----------------------------------------------------------------------------
// qtn_core.v -- Ionosphere (QTN spectroscopy) module, EDDI-FPGA
//
// WHAT THIS IS
//   The full frequency-domain science pipeline, glued together:
//
//     sample stream --> [ Hann window ] --> [ fft_r2 ] --> [ psd_avg ]
//        (ADC)            x hann[n]          FFT/N           mean |X|^2
//
//   This is the FPGA replacement for the LPC4370 flight firmware's QTN
//   modes (512/1024-pt FFT, several frames averaged into one PSD per
//   second). The averaged PSD's spectral peak sits at the local plasma /
//   upper-hybrid frequency -> electron density; its shape -> temperature.
//
// WHY THE HANN WINDOW
//   The FFT assumes each N-sample frame repeats periodically. A raw chop
//   of a continuous signal creates a jump at the frame edge, smearing
//   power across all bins ("spectral leakage") -- fatal when the science
//   is locating one narrow peak. The Hann window (a raised cosine that
//   tapers to zero at both ends) removes the edge discontinuity. The
//   window coefficients are Q1.15 values in a ROM, matching the flight
//   firmware's choice of window.
//
// OPERATION
//   Accepts NAVG frames of N samples over a ready/valid handshake
//   (sample_ready throttles the source: it drops between frames while
//   the FFT is busy, and stays low once the average is complete).
//   When `spectrum_ready` rises, the mean PSD (bins 0..N/2, 32-bit) can
//   be read out via psd_rd_addr/psd_rd_data. Pulse `restart` (while
//   spectrum_ready is high) to clear the average and begin a new one --
//   that pairing is what gives the 1-spectrum-per-second cadence when a
//   1 Hz tick drives restart.
//-----------------------------------------------------------------------------
module qtn_core #(
    parameter LOG2N     = 10,
    parameter N         = 1 << LOG2N,
    parameter LOG2AVG   = 2,               // frames averaged = 1 << LOG2AVG
    parameter HANN_FILE  = "mem/hann_1024.mem",
    parameter TW_RE_FILE = "mem/tw_re_1024.mem",
    parameter TW_IM_FILE = "mem/tw_im_1024.mem"
) (
    input  wire               clk,
    input  wire               rst,
    input  wire               restart,       // clear PSD, start new average

    input  wire               sample_valid,
    input  wire signed [15:0] sample_in,
    output wire               sample_ready,

    output wire               spectrum_ready,
    input  wire [LOG2N-1:0]   psd_rd_addr,
    output wire [31:0]        psd_rd_data,   // valid 2 cycles after addr

    output wire               busy
);

    localparam NAVG = 1 << LOG2AVG;

    // ------------------------------------------------------------- Hann ROM
    // hann[n] = 0.5*(1 - cos(2*pi*n/N)) in Q1.15, generated by
    // fpga/sim/gen_vectors.py. Same $readmemh caveat as the FFT's twiddle
    // ROM: PolarFire LSRAM power-up init must be checked in Libero.
    reg signed [15:0] hann_rom [0:N-1];
    initial $readmemh(HANN_FILE, hann_rom);

    // ------------------------------------------------------------- frame control
    reg [LOG2N-1:0]   n;            // sample index within frame (= ROM addr)
    reg               frame_wait;   // frame fully accepted, FFT still busy
    reg [LOG2AVG:0]   fcnt;         // frames accepted this averaging run
    reg               all_loaded;   // NAVG-th frame accepted: no more samples.
                                    // Needed because spectrum_ready lags the
                                    // last sample by the FFT+PSD latency --
                                    // gating on spectrum_ready alone would
                                    // leak one extra sample in (a bug the
                                    // code review actually caught in sim).

    wire fft_ready;
    wire fft_out_last;

    // restart is only honoured when idle: clearing the accumulator while
    // FFT bins are still streaming into it would mix old and new averages
    wire restart_eff = restart && spectrum_ready;

    // Accept a sample only when ALL of:
    //   fft_ready       - the FFT is in its load state
    //   !frame_wait     - the previous frame's FFT has finished
    //   !all_loaded     - the averaging run still needs frames
    //   !spectrum_ready - a finished spectrum isn't waiting to be read
    assign sample_ready = fft_ready && !frame_wait && !all_loaded
                          && !spectrum_ready;
    wire   accept       = sample_valid && sample_ready;

    // ------------------------------------------------------------- window pipeline
    // Two-stage pipeline in front of the FFT, matching the ROM's 1-clock
    // read latency:
    //   stage 1: register the sample, issue the ROM read for hann[n]
    //   stage 2: multiply sample * coeff, scale Q2.30 -> Q1.15
    // v1/v2 are the valid bits riding alongside; v2 is the FFT's in_valid.
    reg signed [15:0] samp_d;
    reg               v1;
    reg signed [15:0] coeff_q;
    always @(posedge clk) begin
        coeff_q <= hann_rom[n];
        samp_d  <= sample_in;
    end
    // stage 2: multiply, Q1.15 scale (truncating shift -- replicated
    // bit-exactly by the golden model in gen_vectors.py)
    wire signed [31:0] prod = samp_d * coeff_q;
    reg signed [15:0]  win_q;
    reg                v2;

    always @(posedge clk) begin
        if (rst) begin
            n          <= 0;
            frame_wait <= 1'b0;
            fcnt       <= 0;
            all_loaded <= 1'b0;
            v1         <= 1'b0;
            v2         <= 1'b0;
        end else begin
            v1 <= accept;
            v2 <= v1;
            win_q <= prod >>> 15;

            if (accept) begin
                if (n == N-1) begin
                    // frame complete: hold the input off until the FFT has
                    // consumed it (fft_out_last), and note whether this
                    // was the final frame of the averaging run
                    n          <= 0;
                    frame_wait <= 1'b1;
                    fcnt       <= fcnt + 1;
                    if (fcnt == NAVG-1)
                        all_loaded <= 1'b1;
                end else
                    n <= n + 1;
            end

            if (fft_out_last)
                frame_wait <= 1'b0;

            if (restart_eff) begin
                fcnt       <= 0;
                all_loaded <= 1'b0;
            end
        end
    end

    // ------------------------------------------------------------- FFT
    wire               fft_out_valid;
    wire [LOG2N-1:0]   fft_out_bin;
    wire signed [15:0] fft_out_re, fft_out_im;
    wire               fft_busy;

    fft_r2 #(
        .LOG2N(LOG2N),
        .TW_RE_FILE(TW_RE_FILE),
        .TW_IM_FILE(TW_IM_FILE)
    ) u_fft (
        .clk      (clk),
        .rst      (rst),
        .in_valid (v2),
        .in_re    (win_q),
        .in_ready (fft_ready),
        .out_valid(fft_out_valid),
        .out_bin  (fft_out_bin),
        .out_re   (fft_out_re),
        .out_im   (fft_out_im),
        .out_last (fft_out_last),
        .busy     (fft_busy)
    );

    // ------------------------------------------------------------- PSD averaging
    // The FFT's unload stream feeds psd_avg directly; psd_avg's `done` IS
    // this module's spectrum_ready, and restart_eff clears it for the
    // next averaging period.
    psd_avg #(
        .LOG2N  (LOG2N),
        .LOG2AVG(LOG2AVG)
    ) u_psd (
        .clk     (clk),
        .rst     (rst),
        .clear   (restart_eff),
        .in_valid(fft_out_valid),
        .in_bin  (fft_out_bin),
        .in_re   (fft_out_re),
        .in_im   (fft_out_im),
        .in_last (fft_out_last),
        .done    (spectrum_ready),
        .rd_addr (psd_rd_addr),
        .rd_data (psd_rd_data)
    );

    assign busy = fft_busy || frame_wait;

endmodule
