#!/usr/bin/env python3
"""Generate ROM init files and golden test vectors for the EDDI-FPGA testbenches.

Run from fpga/sim:  python gen_vectors.py
Writes .mem files (hex, one value per line) into fpga/sim/mem/ and a
tb_params.vh define file consumed by the testbenches.

Fixed-point conventions (must match the RTL exactly):
  - samples          : signed 16-bit (ADC LSB units)
  - Hann coeffs      : Q1.15, window multiply = (sample * coeff) >>> 15 (floor)
  - twiddles W_N^k   : Q1.15, W = exp(-j*2*pi*k/N)
  - FFT              : radix-2 DIT, 1/2 scaling per stage => output = FFT/N
  - PSD              : re^2 + im^2 (LSB^2), mean over NAVG frames (NAVG = 2^m)
"""
import numpy as np
import os

N = 1024
LOG2N = 10
NAVG = 4          # frames averaged in tb_qtn (power of 2)
TONE_BIN = 77     # ~3.008 MHz at 40 Msps
TONE_AMP = 0.45   # of full scale

os.makedirs("mem", exist_ok=True)
rng = np.random.default_rng(1)


def hex16(v):
    return format(int(v) & 0xFFFF, "04x")


def wr16(path, vals):
    with open(path, "w") as f:
        f.write("\n".join(hex16(v) for v in vals) + "\n")


def s16(x):
    return np.clip(np.round(x), -32768, 32767).astype(np.int64)


# ---------------------------------------------------------------- ROMs
hann = np.round(0.5 * (1 - np.cos(2 * np.pi * np.arange(N) / N)) * 32767).astype(np.int64)
wr16("mem/hann_1024.mem", hann)

k = np.arange(N // 2)
tw = np.exp(-2j * np.pi * k / N)
wr16("mem/tw_re_1024.mem", s16(tw.real * 32767))
wr16("mem/tw_im_1024.mem", s16(tw.imag * 32767))

# ---------------------------------------------------------------- FFT test vector
frames_raw = []
for f in range(NAVG):
    x = TONE_AMP * 32767 * np.sin(2 * np.pi * TONE_BIN * np.arange(N) / N + 0.7 * f)
    x = x + rng.uniform(-64, 64, N)
    frames_raw.append(s16(x))

# tb_fft feeds pre-windowed samples (window is outside the FFT module)
win0 = (frames_raw[0] * hann) >> 15          # arithmetic shift, matches RTL
wr16("mem/fft_in.mem", win0)

gold0 = np.fft.fft(win0.astype(float)) / N   # matches RTL 1/2-per-stage scaling
wr16("mem/fft_gold_re.mem", s16(gold0.real))
wr16("mem/fft_gold_im.mem", s16(gold0.imag))

# ---------------------------------------------------------------- QTN test vector
wr16("mem/qtn_in.mem", np.concatenate(frames_raw))

psds = []
for fr in frames_raw:
    w = (fr * hann) >> 15
    X = np.fft.fft(w.astype(float)) / N
    psds.append(np.abs(X[: N // 2 + 1]) ** 2)
mean_psd = np.mean(psds, axis=0)
peak_bin = int(np.argmax(mean_psd))
peak_pow = float(mean_psd[peak_bin])
assert peak_bin == TONE_BIN, f"peak at {peak_bin}, expected {TONE_BIN}"
# a quiet reference bin far from the tone
quiet_bin = 400
quiet_max = int(peak_pow / 100)

# ---------------------------------------------------------------- debris test vector
DEB_LEN = 45000
SPIKE_AT = 20000
SPIKE_F = 1500.0        # Hz
SPIKE_TAU = 0.004       # s
FS_DEB = 50000.0

noise = rng.uniform(-100, 100, DEB_LEN)      # bounded => no false 4-sigma triggers
deb = 1000.0 + noise
t = np.arange(4000) / FS_DEB
spike = 2000.0 * np.exp(-t / SPIKE_TAU) * np.sin(2 * np.pi * SPIKE_F * t)
deb[SPIKE_AT : SPIKE_AT + 4000] += spike
wr16("mem/debris_stim.mem", s16(deb))

# ---------------------------------------------------------------- params header
with open("mem/tb_params.vh", "w") as f:
    f.write(f"""// auto-generated by gen_vectors.py -- do not edit
`define TB_N          {N}
`define TB_LOG2N      {LOG2N}
`define TB_NAVG       {NAVG}
`define TB_TONE_BIN   {TONE_BIN}
`define QTN_PEAK_MIN  {int(peak_pow * 0.70)}
`define QTN_PEAK_MAX  {int(peak_pow * 1.30)}
`define QTN_QUIET_BIN {quiet_bin}
`define QTN_QUIET_MAX {quiet_max}
`define DEB_LEN       {DEB_LEN}
`define DEB_SPIKE_AT  {SPIKE_AT}
""")

print(f"OK  peak_bin={peak_bin}  peak_pow={peak_pow:.1f}  quiet_max={quiet_max}")
